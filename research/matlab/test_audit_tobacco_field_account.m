function test_audit_tobacco_field_account()
% Synthetic accounting fixtures, not field evidence.
% Attribution:
% bostrom18sd2ujv24ual9c9pshtxys6j8knh6xaead9ye7

stock = struct( ...
    "start",100, ...
    "observedEnd",115, ...
    "deposited",30, ...
    "transportedIn",5, ...
    "collected",10, ...
    "transportedOut",8, ...
    "categoryLoss",2, ...
    "stockUnit","count");

runoff = table( ...
    [0;10;20], [2;2;2], [3;3;3], [1;1;1], ...
    "VariableNames",["timeSeconds","flowLitresPerSecond", ...
    "concentrationMgPerL","backgroundMgPerL"]);

source = struct( ...
    "sourceCitation","synthetic regression fixture", ...
    "boundaryDescription","hypothetical 10 square metre plot", ...
    "observationDate","2026-10-31", ...
    "stockCategory","whole discarded filtered butts", ...
    "contaminantName","synthetic analyte", ...
    "samplingAndInterpolationDescription","constant synthetic rates");

r = audit_tobacco_field_account( ...
    stock,10,1,runoff,"wet_weather",source);

assert(r.predictedEndStock == 115);
assert(r.observedMinusPredictedStock == 0);
assert(r.endDensityPerM2 == 11.5);
assert(abs(r.runoffVolumeLitres-40) < 1e-12);
assert(abs(r.measuredContaminantLoadGrams-0.12) < 1e-12);
assert(abs(r.signedIncrementalLoadGrams-0.08) < 1e-12);

negativeBackgroundDifference = runoff;
negativeBackgroundDifference.backgroundMgPerL(:) = 4;
n = audit_tobacco_field_account( ...
    stock,10,1,negativeBackgroundDifference,"wet_weather",source);
assert(n.signedIncrementalLoadGrams < 0);

inconsistent = stock;
inconsistent.collected = 1000;
bad = audit_tobacco_field_account( ...
    inconsistent,10,1,runoff,"wet_weather",source);
assert(~bad.predictedStockNonnegative);
assert(~bad.sourceAttributionEstablished);
end
